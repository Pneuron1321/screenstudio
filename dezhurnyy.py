def temy_fill(a, rows):
    """ЗАПАС ТЕМ ВПЕРЁД — сердце беседы и её экономика.
    Реплика каждые полминуты — это тридцать вызовов в час; на подписке Pro
    это выжгло бы всё за десять минут вместе с Claude Code. Поэтому один
    вызов даёт не реплику, а ДВЕНАДЦАТЬ тем; дальше они выдаются по одной
    БЕЗ вызовов вообще. Расход падает примерно вдесятеро.
    Побочная выгода важнее экономии: реплика из запаса звучит мгновенно, а
    не через шесть секунд ожидания ответа."""
    parts = []
    st = brief_state(rows)
    if st:
        parts.append('Состояние эфира: ' + st)
    steno = steno_tail(20)
    if steno:
        parts.append('Что стример говорил в этот эфир:\n' + '\n'.join(steno))
    # память прошлых эфиров — то, чего не знает ни один зритель
    try:
        today = 'stenogramma-%s.md' % time.strftime('%Y-%m-%d')
        prev = sorted(f for f in glob.glob(os.path.join(LOG_DIR, 'stenogramma-*.md'))
                      if os.path.basename(f) != today)
        if prev:
            with open(prev[-1], encoding='utf-8') as f:
                tail = [l.strip() for l in f if l.strip()][-25:]
            if tail:
                parts.append('Прошлый эфир (%s) — он про это говорил:\n%s'
                             % (os.path.basename(prev[-1])[13:23], '\n'.join(tail)))
    except Exception:
        pass
    zal, zn, zwho = zal_state(rows)
    parts.append('ЗАЛ: %s (%d чел.). %s' % (zal, zn, ZAL_ROLE[zal]))
    св = sam_svodka()
    if св:
        parts.append('ЧТО У ТЕБЯ ЗАХОДИТ (по прошлым разам): ' + св
                     + '\nДавай больше тем того рода, что заходят.')
    ch = recent_chat(rows, 5)
    if ch:
        parts.append('В чате:\n' + '\n'.join(ch))
    сам = sam_pro_sebya()
    if сам:
        parts.append('ЧТО ТЫ ГОВОРИЛ В ПРОШЛЫЕ ЭФИРЫ (и это заходило) — '
                     'не повторяйся, но держи ту же линию:\n' + '\n'.join(сам))
    prompt = sobrat(lico(), parts, a.rol_temy)
    if getattr(a, 'lang_now', 'ru') == 'en':
        prompt += ('\nТЕМЫ ПИШИ ПО-АНГЛИЙСКИ: разговор идёт на английском. '
                   'Простыми живыми фразами, без учебных оборотов.')
    res = ask_claude(prompt, a.timeout, a.tools, a.test, a.model_temy)
    answer, err = res if isinstance(res, tuple) else (res, None)
    if err:
        log('✗ запас тем: ' + err)
        return []
    lines, gotovoe = [], {}
    for raw in (answer or '').splitlines():
        s = re.sub(r'^\s*\d+[\).\s-]*', '', raw).strip()
        m = re.match(r'^\[(\w+)\]\s*(.+)$', s)
        if m:
            # заготовка на случай: кладём по метке, а не в общую очередь
            gotovoe[m.group(1).lower()] = clean_for_voice(m.group(2), 200)
            continue
        s = clean_for_voice(s, 200)
        if len(s) > 8:
            lines.append(s)
    if gotovoe:
        try:
            with open(os.path.join(LOG_DIR, 'zapas.json'), 'w', encoding='utf-8') as f:
                json.dump(gotovoe, f, ensure_ascii=False)
        except Exception:
            pass
    log('◆ запас: тем %d, заготовок %d (%s)'
        % (len(lines), len(gotovoe), ', '.join(gotovoe.keys()) or '—'))
    return lines[:14]


def razbor_run(a):
    """Разбор полёта: что осталось от эфира — в один честный отчёт.
    Файл пишет ДЕЖУРНЫЙ, а не Клод: руки Клода намеренно узкие (только
    efir-cmd и efir-say), и расширять их ради отчёта не стоит."""
    log('📋 разбор полёта: собираю, что осталось от эфира')
    # журнал посуточный: через полночь берём и вчерашний хвост,
    # иначе весь эфир до 00:00 пропадёт из виду
    rows = rows_svezhie(4000)

    def ops(name):
        return [r.get('data') or {} for r in rows if (r.get('data') or {}).get('op') == name]

    marks = ops('mark')
    tips = ops('tip')
    sovety = ops('sovet')
    events = ops('chat-event')
    chat = ops('chat')
    moments = ops('moment')
    notes = [d for d in ops('note') if isinstance(d.get('data'), str)]

    parts = []
    if rows:
        t0, t1 = rows[0].get('t', ''), rows[-1].get('t', '')
        parts.append('Эфир: с %s по %s' % (t0[11:16], t1[11:16]))
    св = sam_svodka()
    if св:
        parts.append('ТВОИ СОБСТВЕННЫЕ ХОДЫ в этом эфире: ' + св)
    ит = itogi_tail()
    if ит:
        parts.append('ПРОШЛЫЕ ЭФИРЫ (кратко):\n' + '\n'.join(ит))
    steno = steno_tail(120)
    if steno:
        parts.append('СТЕНОГРАММА (что говорил стример):\n' + '\n'.join(steno))
    if marks:
        parts.append('МЕТКИ МОМЕНТОВ: ' + '; '.join(
            str(m.get('recStr') or m.get('airStr') or m.get('clock') or '')
            + ' ' + str(m.get('text') or '') for m in marks[-12:]))
    if moments:
        parts.append('ЛОВЕЦ ОТМЕТИЛ: %d раз (%s)' % (
            len(moments), ', '.join(str(m.get('kind', '')) for m in moments[-6:])))
    if tips:
        summa = sum(float(t.get('amount') or 0) for t in tips)
        parts.append('ДОНАТЫ: %d штук на %.2f (%s)' % (
            len(tips), summa, ', '.join('%s %s' % (t.get('user'), t.get('amount')) for t in tips[-8:])))
    if events:
        parts.append('СОБЫТИЯ КАНАЛА: ' + '; '.join(
            '%s %s' % (e.get('kind'), e.get('user') or '') for e in events[-10:]))
    if sovety:
        parts.append('СОВЕТЫ ЗАЛА: ' + '; '.join(
            '%s: %s' % (s.get('user'), chuzhoe(s.get('text'), 140))
            for s in sovety[-10:]))
    zach = [n['data'] for n in notes if n['data'].startswith('zachet:')]
    if zach:
        parts.append('ЗАЧТЕНО: ' + '; '.join(zach[-6:]))
    goal = [n['data'] for n in notes if n['data'].startswith('goal-done')]
    if goal:
        parts.append('ЦЕЛЬ ВЗЯТА: ' + '; '.join(goal))
    parts.append('Сообщений в чате: %d' % len(chat))

    if len(parts) <= 2:
        log('· разбирать нечего: журнал пуст')
        say('разбирать пока нечего — журнал эфира пуст')
        return

    prompt = '\n\n'.join(parts) + '\n\n' + a.rol_razbor
    res = ask_claude(prompt, max(a.timeout, 90), a.tools, a.test, a.model_razbor)
    answer, err = res if isinstance(res, tuple) else (res, None)
    if err:
        log('✗ разбор: ' + err)
        say('разбор не вышел: ' + err)
        return
    text = (answer or '').strip()
    if not text:
        say('разбор пустой')
        return
    path = os.path.join(LOG_DIR, 'razbor-%s.md' % time.strftime('%Y-%m-%d'))
    try:
        os.makedirs(LOG_DIR, exist_ok=True)
        with open(path, 'a', encoding='utf-8') as f:
            f.write('\n## Разбор ' + time.strftime('%H:%M') + '\n\n' + text + '\n')
        log('📋 разбор записан: ' + path)
        # одна сжатая строка в общую летопись: разбор живёт днём, а
        # летопись — неделями, и её видит разогрев следующего эфира
        сжат = ' '.join(text.split())[:220]
        зал, зн, _ = zal_state(rows)
        with open(os.path.join(LOG_DIR, 'itogi.md'), 'a', encoding='utf-8') as f:
            f.write('- %s · зал %s (%d) · %s\n'
                    % (time.strftime('%d.%m'), зал, зн, сжат))
    except Exception as e:
        log('✗ разбор не сохранился: %s' % e)
    # голосом — только начало: остальное читается глазами
    head = clean_for_voice(text, 300)
    say(head)
    hronika_add('разбор полёта записан')


def warm_run(a):
    """Разогрев: свежее состояние → факты → разговор в ухо. Диалог дальше
    ведёт обычный дежурный: стример отвечает голосом, Клод уточняет."""
    log('🔥 разогрев: прошу состояние студии')
    zapros = time.strftime('%Y-%m-%dT%H:%M:%S')
    state_ask()
    # ЖДЁМ ОТВЕТА, А НЕ 1.8 С. Фиксированная пауза жила, пока телефон и ноут
    # были соседями по Wi-Fi. 24.09 ноут ушёл в свою сеть: круг рубка →
    # PeerJS → телефон → обратно стал длиннее, и разогрев сказал «состояние
    # не пришло», хотя оно пришло следом. Теперь до 8 с, выход по факту.
    # журнал посуточный: через полночь берём и вчерашний хвост,
    # иначе весь эфир до 00:00 пропадёт из виду
    rows = []
    for _ in range(16):
        time.sleep(0.5)
        rows = rows_svezhie(400)
        if any((r.get('data') or {}).get('op') == 'result'
               and (r.get('data') or {}).get('of') == 'state'
               and (r.get('t') or '') >= zapros for r in rows):
            break
    facts = warm_facts(rows)
    for f in facts:
        log('   · ' + f)
    prompt = ('Машинные факты о готовности студии к эфиру:\n'
              + '\n'.join('· ' + f for f in facts) + '\n\n' + a.rol_warm)
    res = ask_claude(prompt, a.timeout, a.tools, a.test, a.model_warm)
    answer, err = res if isinstance(res, tuple) else (res, None)
    if err:
        log('✗ разогрев: ' + err)
        say('разогрев не вышел: ' + err)
        return
    voice = clean_for_voice(answer or '', 420)
    if not voice:
        say('всё готово, можно стартовать')
        return
    log('🔥 ' + voice[:120])
    say(voice)
    hronika_add('разогрев: ' + voice[:110])


