ASK_HEAD = ('Во входном потоке — материал и указание, что с ним делать. '
            'Ответь по нему, ничего не спрашивая.')
CLAUDE_BIN = 'claude'          # переопределяется флагом --claude
PERM_MODE = 'acceptEdits'      # переопределяется флагом --perm


def ask_claude(prompt, timeout, tools, test, model=None):
    """model — алиас (haiku/sonnet/opus) или полное имя. Каждый вызов идёт в
    квоту подписки, поэтому тактовый напарник должен звать самую дешёвую
    модель, а редкие важные ответы — сильную."""
    if test:
        time.sleep(0.2)
        return 'принял, слышу тебя'
    # Windows ставит Claude Code как claude.cmd, а CreateProcess дописывает
    # только .exe — поэтому имя разрешаем сами, а не надеемся на систему.
    #
    # ПРОМПТ ИДЁТ ЧЕРЕЗ STDIN, а не аргументом. Причина не в красоте: длинные
    # многострочные аргументы на Windows ломаются по дороге через оболочку —
    # разбор полёта тащит в промпт всю стенограмму, и он бы просто не дошёл.
    # Стандартный способ Claude Code это и есть: `cat file | claude -p "…"`,
    # где stdin — материал, а -p — что с ним делать. Заодно закрывается вторая
    # беда: без input= дочерний процесс наследует наш stdin и может повиснуть,
    # ожидая ввода, которого не будет.
    cmd = claude_cmd(ASK_HEAD, model, tools, CLAUDE_BIN, PERM_MODE)
    if not cmd:
        return (None, 'claude не найден в PATH — проверь установку Claude Code')
    try:
        r = subprocess.run(cmd, input=prompt.encode('utf-8'),
                           capture_output=True, timeout=timeout, cwd=BASE)
    except FileNotFoundError:
        return None, 'claude не найден в PATH'
    except subprocess.TimeoutExpired:
        return None, 'Клод думал дольше %d с' % timeout
    out = (r.stdout or b'').decode('utf-8', 'replace').strip()
    err = (r.stderr or b'').decode('utf-8', 'replace').strip()
    if r.returncode != 0 and not out:
        return None, (err[-160:] or 'код %d' % r.returncode)
    return out, None


def clean_for_voice(txt, limit=300):
    """к голосу: без разметки, без ссылок, коротко"""
    t = re.sub(r'```.*?```', ' ', txt, flags=re.S)
    t = re.sub(r'https?://\S+', ' ссылка ', t)
    t = re.sub(r'[*_`#>|]', '', t)
    t = re.sub(r'\s+', ' ', t).strip()
    if len(t) > limit:
        cut = t[:limit]
        dot = max(cut.rfind('.'), cut.rfind('!'), cut.rfind('?'))
        t = cut[:dot + 1] if dot > 80 else cut
    return t.strip()


