def uborka(dney=60, test=False):
    """УБОРКА ЖУРНАЛОВ — по возрасту, а не по объёму.

    Проверено числами: за сто трёхчасовых эфиров набегает около 120 МБ, и
    скорость не страдает — читаются всегда последние файлы. Значит уборка
    нужна не ради диска и не ради быстроты, а ради ПОРЯДКА: через год в
    папке шестьсот файлов, и человек, заглянувший туда, не найдёт нужного.

    ЧТО НЕ ТРОГАЕМ НИКОГДА, даже если старое:
    · razbor-*.md и itogi.md — это выводы, ради которых всё и делалось;
    · naedine-*.md — закрытые разговоры, их стирать не наше дело;
    · sovet.json, kto.json, sam.json — накопленное доверие и опыт.
    Убираем только сырьё: события, стенограммы, речи, хронику — то, что
    уже сжато в разбор.
    """
    СЫРЬЁ = ('events-', 'stenogramma-', 'rechi-', 'hronika-')
    порог = time.time() - dney * 86400
    убрано, освобождено = [], 0
    try:
        for имя in os.listdir(LOG_DIR):
            if not имя.startswith(СЫРЬЁ):
                continue
            п = os.path.join(LOG_DIR, имя)
            try:
                if os.path.getmtime(п) >= порог:
                    continue
                освобождено += os.path.getsize(п)
                if not test:
                    os.remove(п)
                убрано.append(имя)
            except OSError:
                pass
    except OSError:
        return [], 0
    return убрано, освобождено


def rows_svezhie(n=400, sec=7200):
    """СТРОКИ ЖУРНАЛА, НЕ ПРИВЯЗАННЫЕ К КАЛЕНДАРЮ.

    Журнал посуточный: events-ДАТА.jsonl. В полночь рубка начинает новый
    файл, дежурный переключается — и весь эфир до полуночи ИСЧЕЗАЕТ.
    Пропадает разом: память эфира, состояние зала, ритм, исходы реплик.
    Начал в 23:00 — в 00:01 Плюс уверен, что эфир только что начался.

    Проявляется раз в сутки и только у ночного эфира, поэтому кольцо этого
    не видело: оно гоняется днём.

    Здесь берём хвост сегодняшнего файла и, если эфир начался вчера, —
    хвост вчерашнего. Отбираем по времени, а не по имени файла.
    """
    строки = []
    сегодня = time.strftime('%Y-%m-%d')
    вчера = time.strftime('%Y-%m-%d', time.localtime(time.time() - 86400))
    for д in (вчера, сегодня):
        ф = os.path.join(LOG_DIR, 'events-%s.jsonl' % д)
        if not os.path.exists(ф):
            continue
        for l in tail_lines(ф, n):
            try:
                строки.append(row_norm(json.loads(l)))
            except Exception:
                pass
    if not строки:
        return строки
    порог = time.strftime('%Y-%m-%dT%H:%M:%S',
                          time.localtime(time.time() - sec))
    свежие = [r for r in строки if (r.get('t') or '') >= порог]
    return (свежие or строки)[-n:]


def row_norm(r):
    """ОДНИ ЧАСЫ НА ВЕСЬ ЖУРНАЛ. Найдено 25.09.26 по живому логу.
    Рубка пишет время по UTC (toISOString, «…Z»), мост и дежурный —
    местное. Дежурный срезал «Z» и читал UTC как местное: в Хорватии каждая
    строка рубки казалась на 1–2 часа старше. Отсюда: свежие советы зала
    отсекались, звуковой портрет был пуст, «без вех 40 мин» через 25 минут
    после старта, исход реплик не видел реакции чата. Кольцо этого не
    видело: песочница живёт в UTC, где двое часов совпадают.
    Чиним на входе: любое «…Z» переводим в местное, дальше всё как было."""
    try:
        t = r.get('t')
        if isinstance(t, str) and t.endswith('Z'):
            r['t'] = time.strftime('%Y-%m-%dT%H:%M:%S',
                                   time.localtime(calendar.timegm(
                                       time.strptime(t[:19], '%Y-%m-%dT%H:%M:%S'))))
    except Exception:
        pass
    return r


def tail_lines(path, n):
    try:
        with open(path, encoding='utf-8') as f:
            return f.readlines()[-n:]
    except Exception:
        return []


def brief_state(rows):
    """последний снимок state из журнала — что сейчас с эфиром"""
    for r in reversed(rows):
        d = r.get('data')
        if isinstance(d, dict) and d.get('op') == 'result' and d.get('of') == 'state':
            st = d.get('result') or {}
            bits = []
            # 'most' — эфир через мост. Без него Плюс видел «спокойно»
            # посреди трансляции: twitchOn говорит только про WHIP.
            for k, ru in (('rec', 'запись'), ('twitchOn', 'twitch'), ('most', 'эфир через мост'),
                          ('panic', 'ПАНИКА'),
                          ('autoBlur', 'блюр'), ('micMuted', 'гейт'), ('clipRing', 'кольцо'),
                          ('dash', 'приборы'), ('hero', 'главный')):
                if st.get(k):
                    bits.append(ru + ('' if st[k] is True else '=' + str(st[k])))
            if st.get('cameras'):
                bits.append('камеры: ' + ', '.join(map(str, st['cameras'])))
            return '; '.join(bits) or 'эфир спокоен'
    return None


