def zal_state(rows, sec=300):
    """СКОЛЬКО ЛЮДЕЙ В ЗАЛЕ — по уникальным авторам чата за последние минуты.

    ПРАВИЛО АЛЕКСАНДРА (30.07): зал НЕ ГЛУШИТ Клода. Число зрителей
    меняет, О ЧЁМ он говорит, а не сколько ему молчать. Беседа не
    прекращается и при полном зале — просто советы и события идут вперёд.
    Сколько Клода в эфире, решает человек, а не счётчик.
    """
    cut = time.strftime('%Y-%m-%dT%H:%M:%S', time.localtime(time.time() - sec))
    users = set()
    for r in rows:
        if (r.get('t') or '') < cut:
            continue
        d = r.get('data') or {}
        if d.get('op') == 'chat' and d.get('user'):
            users.add(str(d['user'])[:24])
    n = len(users)
    if n == 0:
        # «ПУСТО» И «НЕ ВИЖУ» — РАЗНЫЕ ВЕЩИ, и путать их опаснее, чем не
        # знать. Рубка читает чат только Twitch; если эфир ушёл через мост
        # на другую площадку, зрителей может быть сто, а чата не будет ни
        # строки. Раньше Плюс уверенно вёл бы себя как в пустом зале.
        if most_kuda(rows):
            return 'не вижу', 0, []
        return 'пусто', n, sorted(users)
    if n <= 3:
        return 'редкий', n, sorted(users)
    if n <= 12:
        return 'живой', n, sorted(users)
    return 'полный', n, sorted(users)


