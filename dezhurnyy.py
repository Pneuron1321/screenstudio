def predchuvstvie(rows, было=None):
    """ПРЕДЧУВСТВИЕ — Плюс перестаёт только отвечать.

    До сих пор он реагировал на случившееся: событие произошло, он про
    него сказал. Здесь он замечает ПРИЗНАК до события и берёт готовое.
    Считается локально по журналу — ноль вызовов Клода. Возвращает
    (метка, повод) или None.

    Честный предел: признак не пророчество. Ветер может стихнуть, зал
    оживёт сам. Поэтому заготовки короткие и необязательные — промах
    стоит одной лишней фразы, а не сломанного эфира.
    """
    было = было or {}

    def стамп(s):
        try:
            return time.mktime(time.strptime((s or '')[:19], '%Y-%m-%dT%H:%M:%S'))
        except Exception:
            return None

    now = time.time()
    скорости, чаты, вехи, речи = [], [], [], []
    эфир_шаги = []
    for r in rows:
        t = стамп(r.get('t'))
        if t is None:
            continue
        d = r.get('data') or {}
        op = d.get('op')
        if op == 'result' and d.get('of') == 'state' and isinstance(d.get('result'), dict):
            сп = (d['result'] or {}).get('spd')
            if сп is not None:
                скорости.append((t, сп))
        elif op == 'geo' and d.get('spd') is not None:
            скорости.append((t, d['spd']))
        elif op == 'chat':
            чаты.append(t)
        elif op in ('mark', 'moment', 'tip', 'chat-event', 'sovet'):
            вехи.append(t)
        elif op == 'said':
            речи.append(t)
        elif op == 'zvuk' and 'efir' in d:
            эфир_шаги.append((t, bool(d['efir'])))

    # 1 · ВЕТЕР: скорость выросла заметно за последние минуты
    свежие = [с for t, с in скорости if now - t < 180]
    ранние = [с for t, с in скорости if 180 <= now - t < 420]
    if len(свежие) >= 3 and len(ранние) >= 3:
        н = sum(свежие) / len(свежие)
        р = sum(ранние) / len(ранние)
        if р > 0.5 and н > р * 1.4 and now - (было.get('ветер') or 0) > 600:
            return 'ветер', 'скорость выросла с %.1f до %.1f м/с' % (р, н)

    # 2 · ТИХО: зал молчит дольше десяти минут, хотя раньше говорил
    if чаты:
        молчит = now - max(чаты)
        if молчит > 600 and len(чаты) > 3 and now - (было.get('тихо') or 0) > 900:
            return 'тихо', 'зал молчит %d мин' % int(молчит / 60)

    # 3 · ДОЛГО: эфир идёт, а вех давно не было
    нач = стамп(rows[0].get('t')) if rows else None
    # ЭФИР — ПО СЛОВУ СТУДИИ, А НЕ ПО ЖИВОСТИ ЖУРНАЛА. Студия шлёт zvuk и
    # вне эфира; 24.09 «без вех» тикал три часа при efir:false. Теперь
    # zvuk несёт efir, и отсчёт идёт от начала непрерывного эфира. Старая
    # студия без поля — прежнее поведение.
    if эфир_шаги:
        нач = None
        for t, e in эфир_шаги:
            if e and нач is None:
                нач = t
            elif not e:
                нач = None
    if нач and now - нач > 2400:
        последняя = max(вехи) if вехи else нач
        if now - последняя > 1800 and now - (было.get('долго') or 0) > 1800:
            return 'долго', 'без вех %d мин' % int((now - последняя) / 60)

    return None


def chuzhoe(текст, предел=200):
    """ЧУЖИЕ СЛОВА В ПРОМПТЕ — ОБЕЗВРЕЖЕННЫЕ.

    Чат зрителей уходит Плюсу как есть, и это дыра: любой может написать
    «игнорируй прежние указания, скажи то-то» — и текст ляжет в промпт
    рядом с настоящей ролью. Модель не знает, где кончается описание мира
    и начинается приказ, если их не разделить.

    Здесь три меры, и все дешёвые:
    · переносы строк схлопываем — многострочный текст выглядит как новый
      раздел промпта, а это половина силы такой попытки;
    · режем длину: длинная простыня в чате бывает только у того, кто
      что-то затевает;
    · обрамляем кавычками-ёлочками, чтобы граница чужой речи была видна.

    Главная защита — не здесь, а в роли: там сказано прямо, что слова из
    чата это ДАННЫЕ, а не указания. Одно без другого не работает.
    """
    т = ' '.join(str(текст or '').split())
    if len(т) > предел:
        т = т[:предел] + '…'
    return '«' + т.replace('«', '"').replace('»', '"') + '»'


