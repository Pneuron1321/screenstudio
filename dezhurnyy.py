def hronika_path():
    return os.path.join(LOG_DIR, 'hronika-%s.md' % time.strftime('%Y-%m-%d'))


def hronika_add(line):
    """Память эфира. Безголовый Клод не помнит прошлых вызовов: каждый —
    чистый лист. Поэтому дежурный ведёт короткую хронику и подаёт её хвост
    в контекст. Дешевле бесконечной сессии и не растёт без предела."""
    try:
        os.makedirs(LOG_DIR, exist_ok=True)
        with open(hronika_path(), 'a', encoding='utf-8') as f:
            f.write(time.strftime('%H:%M') + ' · ' + str(line).strip() + '\n')
    except Exception:
        pass


def hronika_tail(n=8):
    try:
        with open(hronika_path(), encoding='utf-8') as f:
            return [l.rstrip() for l in f.readlines()[-n:]]
    except Exception:
        return []


def event_note(d):
    """Не всё подряд: в память идут только вехи эфира."""
    op = d.get('op')
    if op == 'result':
        of, res, err = d.get('of'), d.get('result'), d.get('error')
        if err:
            return 'сбой: %s — %s' % (of, str(err)[:60])
        if of == 'clip':
            return 'вырезан клип: %s' % str(res)[:40]
        if of in ('rec', 'twitch'):
            return '%s: %s' % (of, str(res)[:30])
        return None
    if op == 'chat-event':
        return 'в чате: %s %s' % (d.get('kind', ''), str(d.get('note') or '')[:60])
    if op == 'presence':
        return 'на карте появился %s%s' % (d.get('name', '?'),
                                           (' (%s км)' % d['km']) if d.get('km') else '')
    if op == 'note' and d.get('data') == 'silence':
        return 'в эфире была тишина'
    return None


