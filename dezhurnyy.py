def sobrat(lico_text, parts, role_text=None, predel=40000):
    """СБОРКА ПРОМПТА С ЧЕСТНЫМ ПРЕДЕЛОМ.

    ДВЕ ОШИБКИ, КОТОРЫЕ ЗДЕСЬ ИСПРАВЛЕНЫ (обе мои, 20.08):

    1. ПРЕДЕЛ БЫЛ СЛИШКОМ ЖЁСТКИМ. Я поставил 9000 знаков наугад, а
       измерение показало: настоящий промпт на ЧАСОВОМ эфире — 6190
       знаков, то есть запас был всего сорок процентов. Для модели с
       контекстом в сотни тысяч токенов это крохи. Предел поднят до 40000
       (~10 тысяч токенов) — вшестеро больше живого случая.

    2. ОБОСНОВАНИЕ БЫЛО НЕВЕРНЫМ. Я написал «жжёт квоту»: квота Pro
       считается в ВЫЗОВАХ, а не в знаках, и длина её не тратит. Настоящая
       причина ограничивать — в длинном промпте важное тонет среди
       подробностей, и ответ становится хуже.

    3. РЕЗАТЬ СЕРЕДИНУ — ПЛОХО. В середине может лежать что угодно, в том
       числе «Стример сказал вслух». Теперь жертвуем ПО ПОРЯДКУ ЦЕННОСТИ:
       сперва карта зала, потом память о себе, потом стенограмма. Ядро —
       личность, роль, слова стримера, состояние эфира — не трогаем
       никогда.
    """
    голова = 'КТО ТЫ:\n' + lico_text + '\n\n'
    хвост = ('\n\n' + role_text) if role_text else ''
    куски = list(parts)
    свободно = predel - len(голова) - len(хвост)
    убрано = []

    def длина():
        return len('\n\n'.join(куски))

    for метка in PODROBNOSTI:
        if длина() <= свободно:
            break
        for i, к in enumerate(куски):
            if str(к).startswith(метка):
                куски.pop(i)
                убрано.append(метка.lower())
                break

    тело = '\n\n'.join(куски)
    # если и после этого длинно — виновата одна огромная часть: режем её
    if len(тело) > свободно > 400:
        тело = тело[:свободно] + '\n…(дальше обрезано)'
        убрано.append('хвост')
    if убрано:
        тело += ('\n\nПРОМПТ БЫЛ ДЛИННЫМ, убрал: ' + ', '.join(убрано)
                 + '. Если чего-то не хватает — скажи стримеру, не выдумывай.')
    return голова + тело + хвост


