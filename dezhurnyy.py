def zvuk_svodka(rows, sec=120):
    """ЗВУКОВОЙ ПОРТРЕТ — характер эфира на слух, которого у Клода не было.
    Студия шлёт сводку раз в 12 секунд; берём свежие и складываем в строку.
    Честный предел: это характер звука, а не звук — по нему не понять,
    смешно ли было, только что было громко, часто и рвано."""
    cut = time.strftime('%Y-%m-%dT%H:%M:%S', time.localtime(time.time() - sec))
    свежие = []
    for r in rows:
        if (r.get('t') or '') < cut:
            continue
        d = r.get('data') or {}
        if d.get('op') == 'zvuk':
            свежие.append(d)
    if not свежие:
        return None
    слово = свежие[-1].get('slovo') or ''
    if len(свежие) > 3:
        пол = len(свежие) // 2
        ран = sum(x.get('sredn') or 0 for x in свежие[:пол]) / max(1, пол)
        поз = sum(x.get('sredn') or 0 for x in свежие[пол:]) / max(1, len(свежие) - пол)
        if поз > ран * 1.5:
            слово += ', звук нарастает'
        elif ран > поз * 1.5:
            слово += ', звук стихает'
    return слово


