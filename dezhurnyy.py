def ruki_probe(a, tools, perm, probe):
    """Одна попытка: дать Клоду набор прав и посмотреть, лёг ли файл.
    Проверяем диском, а не словами: Клод честно отвечает «есть» и когда
    записать не смог — разрешения до него просто не дошли."""
    cmd_dir = os.path.join(BASE, 'efir-cmd')
    done_dir = os.path.join(cmd_dir, 'done')
    os.makedirs(cmd_dir, exist_ok=True)
    prompt = ('Создай файл efir-cmd/%s с ровно таким содержимым: '
              '{"op":"cmd","name":"state","args":[]} — и ответь одним '
              'словом «есть». Больше ничего не делай.' % probe)
    global PERM_MODE
    was, PERM_MODE = PERM_MODE, perm
    try:
        res = ask_claude(prompt, max(a.timeout, 60), tools, False, a.model_napar)
    finally:
        PERM_MODE = was
    answer, err = res if isinstance(res, tuple) else (res, None)
    if err:
        return None, err
    alive = os.path.exists(os.path.join(cmd_dir, probe))
    if not alive:
        try:
            alive = any(f.endswith(probe) for f in os.listdir(done_dir))
        except OSError:
            pass
    if alive:
        try:
            os.remove(os.path.join(cmd_dir, probe))
        except OSError:
            pass
    return alive, (answer or '')


