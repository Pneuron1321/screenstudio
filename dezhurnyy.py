    for r in rows:
        d = r.get('data') or {}
        if d.get('op') != 'sovet':
            continue
        if (r.get('t') or '') < порог:     # обещанные пять минут — теперь на деле
            continue
        ves = d.get('ves') or 0
        silen = d.get('silen') or ''
        mark = ''
        if ves:
            mark = ' [доверие %d%s]' % (ves, (' · силён: ' + silen) if silen else '')
        else:
            mark = ' [новичок]'
        out.append('%s%s: %s' % (d.get('user', 'кто-то'), mark, d.get('text', '')))
    return out[-n:]


