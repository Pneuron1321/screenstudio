    ap.add_argument('--model-napar', default='haiku',
                    help='модель напарника: тактовые вызовы, нужна дешёвая и быстрая')
    ap.add_argument('--model-warm', default='sonnet',
                    help='модель разогрева: раз в эфир, нужен разбор фактов')
    ap.add_argument('--no-eye', dest='eye', action='store_false',
                    help='напарнику не просить кадров — только чат и память')
    a = ap.parse_args()

    # ОДИН ДЕЖУРНЫЙ НА ПРОЕКТ. Второй запуск — тихая беда: оба читают один
    # журнал, оба отвечают на одну фразу, оба тратят квоту, и Плюс говорит
    # дважды. Найти причину в эфире невозможно — выглядит как «он повторяет
    # сам себя». Поэтому проверяем ясно и сразу.
    метка = os.path.join(LOG_DIR, 'dezhurnyy.pid')
    try:
        os.makedirs(LOG_DIR, exist_ok=True)
        if os.path.exists(метка):
            старый = 0
            try:
                with open(метка, encoding='utf-8') as f:
                    старый = int((f.read() or '0').strip() or 0)
            except Exception:
                pass
            живой = False
            if старый and старый != os.getpid():
                try:
                    if os.name == 'nt':
                        живой = str(старый) in subprocess.run(
                            ['tasklist', '/FI', 'PID eq %d' % старый],
                            capture_output=True, text=True).stdout
                    else:
                        os.kill(старый, 0)
                        живой = True
                except Exception:
                    живой = False
            if живой:
                log('✗ ДЕЖУРНЫЙ УЖЕ РАБОТАЕТ (номер %d).' % старый)
                log('  Второй будет отвечать на те же фразы вторым голосом и')
                log('  тратить ту же квоту. Закрой первое окно или убей процесс.')
                log('  Уверен, что первого нет: удали %s' % метка)
                sys.exit(3)      # именно выход с ошибкой, а не тихий возврат
        with open(метка, 'w', encoding='utf-8') as f:
            f.write(str(os.getpid()))
    except Exception:
        pass          # метка — удобство, а не условие работы

    global CLAUDE_BIN, PERM_MODE
    CLAUDE_BIN, PERM_MODE = a.claude, a.perm
    if a.ruki_test:
        sys.exit(ruki_test(a))

    os.makedirs(LOG_DIR, exist_ok=True)
    path = today_log()
    log('дежурный на посту' + (' (проба, без Клода)' if a.test else ''))
    log('руки: ' + (a.tools if a.tools else 'ВЫКЛЮЧЕНЫ — клод только говорит'))
    log('модели: голос → %s · напарник → %s · разогрев → %s'
        % (a.model_duty, a.model_napar, a.model_warm))
    log('журнал: ' + os.path.basename(path))
    log('пауза между вызовами: %.0f с · таймаут: %d с' % (a.pause, a.timeout))
    log('напарник: ' + ('такт %.0f с (в тишине %.0f с), молчит %.0f с после тебя'
                        % (a.takt, a.takt * 3, a.quiet) if a.napar
                        else 'спит — скажи «рут код, напарник»'))

    pos = os.path.getsize(path) if os.path.exists(path) else 0
    last_call, calls, awake = 0, 0, True
    napar, last_takt, takt_new, last_voice, cohost = bool(a.napar), time.time(), 0, 0, False
    naedine = False                      # закрытый разговор: только в ухо, запись отдельно
    # ТУМБЛЕРЫ — ИЗ ИСТОРИИ, А НЕ ТОЛЬКО ИЗ ПЕРЕКЛЮЧЕНИЙ. Дежурный узнавал
    # соведущего лишь в момент нажатия: перезапуск 24.09 посреди эфира — и
    # Плюс говорил только в ухо при включённом тумблере. Берём последнее
    # слово журнала за 6 часов. Ошибись журнал (студию перезагрузили) —
    # студия сама не пустит в эфир и скажет в ухо: права остаются у неё.
    for r in rows_svezhie(3000, 6 * 3600):
        d = r.get('data') or {}
        v = d.get('data') if d.get('op') == 'note' else None
        if v == 'cohost:on':
            cohost = True
        elif v == 'cohost:off':
            cohost = False
        elif v == 'naedine:on':
            naedine, cohost = True, False
        elif v == 'naedine:off':
            naedine = False
    if cohost or naedine:
        log('тумблеры из журнала: ' + ('наедине' if naedine else 'соведущий вкл'))
    beseda = bool(a.beseda)              # собеседник: говорит сам, не ждёт поводов
    temy = temy_load().get('list') or []
    temy_at = 0                          # когда последний раз говорил собеседник
    zal_was = None                       # прошлое состояние зала: переход объявляем словом
    last_zal_check = 0                   # считаем зал не чаще раза в 20 с
    beseda_lang = 'ru'                   # язык беседы: студия скажет, когда сменится
    if a.uborka > 0:
        стёрто, байт = uborka(a.uborka)
        if стёрто:
            log('убрано старого сырья: %d файлов, %d КБ (старше %d дней). '
                'Разборы и итоги на месте.' % (len(стёрто), байт // 1024, a.uborka))
    log('беседа: ' + ('включена, тишина %.0f с' % a.tishina if beseda
                      else 'спит — скажи «поговорим»')
        + (' · запас тем: %d' % len(temy) if temy else ''))

    последний_итог = 0
    последнее_предчувствие = 0
    предчувствия = {}          # когда какой признак срабатывал: не частим
    while True:
        time.sleep(0.7)

        # ---- ИТОГИ СВОИХ СЛОВ: раз в 20 с, независимо от того, работает
        # ли напарник. Раньше это жило внутри такта — и вес считался,
        # только пока Плюс говорил через напарника; реплики беседы и
        # ответов на голос оставались без исхода. Найдено живым прожигом.
        if time.time() - последний_итог > a.itogi:
            последний_итог = time.time()
            # журнал посуточный: через полночь берём и вчерашний хвост,
            # иначе весь эфир до 00:00 пропадёт из виду
            строки = rows_svezhie(300)
            sam_schet(строки)

        # ---- ПРЕДЧУВСТВИЕ: признак замечен — берём готовое ----
        # Плюс перестаёт только отвечать: заготовка лежит наготове и
        # ставится мгновенно, вызова Клода не тратит.
        if awake and time.time() - последнее_предчувствие > 60:
            последнее_предчувствие = time.time()
            # журнал посуточный: через полночь берём и вчерашний хвост,
            # иначе весь эфир до 00:00 пропадёт из виду
            строки_п = rows_svezhie(400)
            п = predchuvstvie(строки_п, предчувствия)
            if п:
                метка, повод = п
                предчувствия[метка] = time.time()
                готовое = zapas_vzyat(метка)
                if готовое:
                    log('◈ предчувствие [%s]: %s' % (метка, повод))
                    rech_zapis(строки_п, 'предчувствие', готовое, {'povod': повод})
                    say(готовое, efir=(cohost and not naedine))
                elif метка == 'титр':
                    pass
                else:
                    log('◈ признак [%s]: %s — заготовки нет' % (метка, повод))

        # ---- БЕСЕДА: тишину подхватывает тема из запаса, без вызова ----
        if beseda and awake:
            now = time.time()
            # зал сменился — говорим об этом вслух, чтобы человек не гадал,
            # почему Клод вдруг стал говорить иначе
            if now - last_zal_check > 20:
                last_zal_check = now
                # журнал посуточный: через полночь берём и вчерашний хвост,
                # иначе весь эфир до 00:00 пропадёт из виду
                rows_z = rows_svezhie(300)
                z, zn, _ = zal_state(rows_z)
                if zal_was is None:
                    zal_was = z
                elif z != zal_was:
                    say({'пусто': 'зал разошёлся — снова вдвоём',
                         'редкий': 'к нам зашли, теперь не одни',
                         'живой': 'зал ожил — держу советы вперёд',
                         'полный': 'зал полон, ухожу в подсказки'}.get(z, 'зал изменился'),
                        efir=False)
                    log('👥 зал: %s → %s (%d чел.)' % (zal_was, z, zn))
                    zal_was = z
            quiet_for = now - max(last_voice, temy_at)
            if quiet_for >= a.tishina:
                if not temy:
                    # журнал посуточный: через полночь берём и вчерашний хвост,
                    # иначе весь эфир до 00:00 пропадёт из виду
                    rows_t = rows_svezhie(300)
                    a.lang_now = beseda_lang     # темы собираются на языке беседы
                    temy = temy_fill(a, rows_t)
                    temy_save({'list': temy, 't': now})
                    calls += 1
                    if calls >= a.budget:
                        beseda = False
                        log('⚠ бюджет исчерпан — беседа умолкает')
                        say('бюджет вызовов кончился, дальше молчу')
                if temy:
                    line = temy.pop(0)
                    temy_save({'list': temy, 't': now})
                    temy_at = now
                    log('💬 ' + line[:90])
                    # rows_t есть только когда запас пополнялся; в остальные
                    # разы читаем журнал сами — контекст реплики важнее экономии
                    # журнал посуточный: через полночь берём и вчерашний хвост,
                    # иначе весь эфир до 00:00 пропадёт из виду
                    rows_r = rows_svezhie(200)
                    rech_zapis(rows_r, 'беседа', line)
                    say(line, efir=(cohost and not naedine))
                    if naedine:
                        naedine_add('клод', line[:200])
                    else:
                        hronika_add('беседа: ' + line[:90])
                else:
                    temy_at = now      # тем нет — не долбим вызовами

        # ---- ТАКТ НАПАРНИКА: повод, а не расписание ----
        if napar and awake:
            now = time.time()
            due = a.takt if takt_new else a.takt * 3      # тишина — смотрим реже
            if (now - last_takt >= due and now - last_call >= a.pause
                    and now - last_voice >= a.quiet):
                last_takt = now
                fa = frame_age()
                if a.eye and (fa is None or fa > a.takt * 0.5):
                    frame_ask()
                    time.sleep(1.6)                       # кадру долететь до диска
                # журнал посуточный: через полночь берём и вчерашний хвост,
                # иначе весь эфир до 00:00 пропадёт из виду
                rows = rows_svezhie(400)
                log('◆ такт напарника (поводов: %d)' % takt_new)
                takt_new = 0
                t0 = time.time()
                last_call = time.time()
                res = ask_claude(build_takt_prompt(rows, a.rol_napar, cohost),
                                 a.timeout, a.tools, a.test, a.model_napar)
                answer, err = res if isinstance(res, tuple) else (res, None)
                if err:
                    log('✗ напарник: ' + err)
                else:
                    calls += 1                            # вызов стоит токенов и молча
                    voice = clean_for_voice(answer or '', 200)
                    bare = re.sub(r'[^а-яёa-z]', '', voice.lower())
                    if not voice or bare in ('тихо', 'молчу', 'пас'):
                        log('· напарник промолчал (его право)')
                    else:
                        log('◆ (%.1f с) %s' % (time.time() - t0, voice[:90]))
                        rech_zapis(rows, 'напарник', voice,
                                   {'efir': bool(cohost and not naedine)})
                        say(voice, efir=(cohost and not naedine))
                        if naedine:
                            naedine_add('клод', voice[:200])
                        else:
                            hronika_add('напарник%s: %s'
                                        % (' в эфир' if cohost else '', voice[:90]))
                    if calls >= a.budget:
                        napar = False
                        log('⚠ бюджет %d вызовов исчерпан — напарник уснул сам' % calls)
                        say('напарник умолкает: бюджет вызовов исчерпан')

        cur = today_log()
        if cur != path:                      # наступил новый день — новый файл
            path, pos = cur, 0
            log('журнал сменился: ' + os.path.basename(path))
        if not os.path.exists(path):
            continue
        size = os.path.getsize(path)
        if size < pos:                        # журнал обрезали
            pos = 0
        if size == pos:
            continue
        with open(path, encoding='utf-8') as f:
            f.seek(pos)
            fresh = f.readlines()
            pos = f.tell()

        for line in fresh:
            try:
                rec = row_norm(json.loads(line))
            except Exception:
                continue
            d = rec.get('data')
            if not isinstance(d, dict):
                continue
            note = event_note(d)          # вехи эфира — тоже память
            if note:
                hronika_add(note)
            if d.get('op') == 'razbor':   # разбор полёта после эфира
                last_call = time.time()
                razbor_run(a)
                calls += 1
                continue
            if d.get('op') == 'warm':     # кнопка 🔥 РАЗОГРЕВ в студии
                last_call = time.time()
                warm_run(a)
                calls += 1
                continue
            if is_povod(d):
                takt_new += 1             # мир изменился — напарнику есть на что смотреть
            if d.get('op') == 'note' and isinstance(d.get('data'), str):
                if d['data'] == 'cohost:on':
                    cohost = True
                elif d['data'] == 'cohost:off':
                    cohost = False
                elif d['data'] == 'naedine:on':
                    naedine, cohost = True, False    # в закрытом разговоре — только в ухо
                    log('🔒 наедине: говорю только в ухо, пишу отдельно')
                elif d['data'] == 'naedine:off':
                    naedine = False
                    log('🔓 снова в эфире')
                elif d.get('op') == 'perevod' and d.get('text'):
                    # перевод идёт вне такта и вне бюджета напарника: это
                    # прямая просьба человека, а не своя инициатива Плюса
                    т = perevod_run(a, d['text'], d.get('yaz'), d.get('имя'))
                    if т:
                        # Дежурный сам команд не кладёт — это руки Клода.
                        # Перевод уходит тем же путём, что голос: файлом,
                        # который читает рубка. Она и передаст студии.
                        try:
                            os.makedirs(CMD_DIR, exist_ok=True)
                            имя_ф = 'perevod-%d.json' % int(time.time() * 1000)
                            with open(os.path.join(CMD_DIR, имя_ф), 'w',
                                      encoding='utf-8') as f:
                                json.dump({'op': 'perevod-gotovo', 'text': т,
                                           'yaz': d.get('yaz')}, f,
                                          ensure_ascii=False)
                        except Exception as e:
                            log('✗ перевод не дошёл: ' + str(e))
                        calls += 1
                elif d['data'].startswith('beseda-lang:'):
                    beseda_lang = d['data'].split(':', 1)[1].strip() or 'ru'
                    log('🗣 язык беседы: ' + beseda_lang)
            if d.get('op') != 'voice':
                continue
            phrase = (d.get('text') or '').strip()
            if not phrase:
                continue
            low = phrase.lower()

            if any(w in low for w in SLEEP_WORDS):
                awake = False
                log('⏸ ухожу в сон по просьбе')
                say('дежурный спит')
                continue
            if any(w in low for w in WAKE_WORDS):
                awake = True
                log('▶ снова на посту')
                say('дежурный на месте')
                continue
            last_voice = time.time()      # стример говорит — напарник не перебивает
            temy_at = last_voice          # и собеседник тоже: он слушает, а не ждёт очереди
            if any(w in low for w in BESEDA_OFF):
                beseda = False
                log('💬 беседа выключена')
                say('молчу')
                continue
            if any(w in low for w in BESEDA_ON):
                beseda, temy_at = True, time.time()
                log('💬 беседа включена')
                say('поговорим')
                continue
            if any(w in low for w in RAZBOR_WORDS):
                last_call = time.time()
                razbor_run(a)
                calls += 1
                continue
            if any(w in low for w in WARM_WORDS):
                last_call = time.time()
                warm_run(a)
                calls += 1
                continue
            if any(w in low for w in NAPAR_OFF):
                napar = False
                log('◆ напарник спит')
                say('напарник спит')
                continue
            if any(w in low for w in NAPAR_ON):
                napar, last_takt = True, time.time()
                log('◆ напарник на посту, такт %.0f с' % a.takt)
                say('напарник рядом')
                continue
            if not awake:
                log('· «%s» — сплю, пропускаю' % phrase[:40])
                continue

            gap = time.time() - last_call
            if gap < a.pause:
                log('· «%s» — слишком часто (%.0f с), пропускаю' % (phrase[:40], gap))
                continue

            rows = []
            for l in tail_lines(path, 400):
                try:
                    rows.append(row_norm(json.loads(l)))
                except Exception:
                    pass

            log('🎙 «%s» → бужу Клода' % phrase[:60])
            t0 = time.time()
            last_call = time.time()
            # роль собеседника не мёртвая бумага: когда беседа идёт, она
            # добавляется к обычной роли — и ответы на голос звучат в том же духе
            rol_now = a.rol + ('\n\n' + a.rol_beseda if beseda else '')
            if beseda_lang == 'en':
                rol_now += ROLE_EN.get(a.en, ROLE_EN['soft'])
            res = ask_claude(build_prompt(phrase, rows, rol_now), a.timeout, a.tools,
                             a.test, a.model_duty)
            answer, err = res if isinstance(res, tuple) else (res, None)
            if err:
                log('✗ ' + err)
                say('не дозвался Клода')
                continue
            voice = clean_for_voice(answer or '')
            if not voice:
                log('· пустой ответ')
                continue
            calls += 1
            log('🗣 (%.1f с) %s' % (time.time() - t0, voice[:90]))
            rech_zapis(rows, 'ответ', voice, {'vopros': phrase[:150]})
            say(voice)
            if naedine:
                # закрытый разговор целиком уходит в свой файл
                naedine_add('я', phrase[:200])
                naedine_add('клод', voice[:200])
            else:
                hronika_add('спросил: %s → ответил: %s' % (phrase[:70], voice[:90]))
            if calls == a.budget:
                log('⚠ вызовов за сессию: %d — присматривай за расходом' % calls)


